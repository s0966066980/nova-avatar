"""Console API of the Matcha training job (all routes are ADMIN, ADR 0021).

``GET  /api/tts/training?corpus=<slug>&name=<name>``  job state, pre-flight checks, settings
``POST /api/tts/training/start``                      start a job (409 with the failed checks)
``POST /api/tts/training/cancel``                     stop the running job
``GET  /api/tts/training/log?offset=<n>``             log lines from absolute line ``n``
``POST /api/tts/training/text-preview``               review an Edge text list before synthesis (pure)
``POST /api/tts/training/preview``                    a preset sentence in a voice model's voice (``audio/wav``)

Request fields name server-managed items only: a corpus by its slug, a preset by its
key, an Edge voice from the fixed list. The voice-model ID is generated by the server.
There is no route that downloads or exports a voice model: it stays in ``models/tts/``
on this machine (spec decision 14). The work happens in ``TrainingJobManager``; every
call that can block (``nvidia-smi``, files, the job thread, synthesis) runs in a worker thread.

The voice preview takes ``{"voice_id", "sentence"}`` where ``sentence`` is one of the codes
of ``src.tts.voice_preview.PREVIEW_SENTENCES``. It accepts no text of its own, speaks on the
CPU through the engine's shared voice-model loader and lock, and answers with a size-limited
inline WAV; the voice model itself is never sent.
"""

from __future__ import annotations

import asyncio
import threading
from collections.abc import Callable
from typing import Any

from aiohttp import web

from src.config.schema import Config
from src.server.routes import tts_corpus
from src.server.state import state
from src.server.tts_training_jobs import (
    StartRequest,
    TrainingError,
    TrainingJobManager,
    settings_from_config,
)
from src.tts.training.corpus import CorpusError
from src.tts.training.edge_acknowledgement import MSA_CLAUSE
from src.tts.training.sentences import review_text_list
from src.tts.voice_preview import PREVIEW_SENTENCES, PreviewError, synthesize_preview
from src.utils.logging import logger

# (voice_id, sentence code, keep_going) -> WAV bytes; blocking, so it runs in a worker thread.
Previewer = Callable[[object, object, Callable[[], bool]], bytes]
MANAGER_KEY = web.AppKey("tts_training_manager", TrainingJobManager)
PREVIEWER_KEY = web.AppKey("tts_voice_previewer", Callable)
PREFIX = "/api/tts/training"
# Loading a voice model for the first time takes several seconds; a preview itself takes far less.
PREVIEW_TIMEOUT_SECONDS = 60.0


def build_manager(app: web.Application | None = None) -> TrainingJobManager:
    """The manager of the running server; its settings follow the live configuration.

    With ``app`` it also learns whether the corpus routes' automatic transcription is
    running (looked up when asked, so the registration order does not matter): a training
    job is refused meanwhile, because both want the same CPU and GPU.
    """

    def transcription_running() -> bool:
        services = None if app is None else app.get(tts_corpus.SERVICES)
        return services is not None and services.jobs.running()

    return TrainingJobManager(
        settings=lambda: settings_from_config(state.config), transcription_active=transcription_running
    )


def live_previewer(voice_id: object, sentence: object, keep_going: Callable[[], bool]) -> bytes:
    """Speak a preset sentence with the thread count of the live configuration."""
    matcha = getattr(state.config, "matcha", None)
    threads = getattr(matcha, "num_threads", None) or Config().matcha.num_threads
    return synthesize_preview(voice_id, sentence, num_threads=int(threads), keep_going=keep_going)


def _json(payload: dict[str, Any], status: int = 200) -> web.Response:
    return web.json_response(payload, status=status)


def _error(message: str, status: int, **extra: Any) -> web.Response:
    return _json({"code": -1, "msg": message, **extra}, status)


def _manager(request: web.Request) -> TrainingJobManager:
    return request.app[MANAGER_KEY]


def _optional_text(payload: dict[str, Any], key: str) -> str | None:
    value = payload.get(key)
    if value is not None and not isinstance(value, str):
        raise TrainingError(f"{key} 必須是文字")
    return value


async def get_status(request: web.Request) -> web.Response:
    manager = _manager(request)
    corpus = request.query.get("corpus") or None
    name = request.query.get("name")

    def collect() -> dict[str, Any]:
        settings = manager.settings()
        return {
            "job": manager.status(),
            "preflight": manager.evaluate_preflight(corpus, name).to_dict(),
            "settings": {
                "min_free_vram_gb": settings.min_free_vram_gb,
                "whisper_model": settings.whisper_model,
                # The console shows and sends back exactly this text; it keeps no copy of its own.
                "edge_clause": {
                    "reference": MSA_CLAUSE.reference,
                    "effective": MSA_CLAUSE.effective,
                    "text": MSA_CLAUSE.text,
                },
            },
        }

    try:
        return _json({"code": 0, "data": await asyncio.to_thread(collect)})
    except CorpusError as exc:
        return _error(exc.message, exc.status)


async def _json_object(request: web.Request) -> dict[str, Any] | web.Response:
    """The request body as an object, or the 400 response to send instead."""
    try:
        payload = await request.json()
    except (ValueError, TypeError):
        return _error("請求格式必須為 JSON", 400)
    if not isinstance(payload, dict):
        return _error("請求格式必須為物件", 400)
    return payload


async def start_job(request: web.Request) -> web.Response:
    payload = await _json_object(request)
    if isinstance(payload, web.Response):
        return payload
    try:
        corpus, name = payload.get("corpus"), payload.get("name")
        if not isinstance(corpus, str) or not corpus:
            raise TrainingError("請選擇訓練語料")
        if not isinstance(name, str):
            raise TrainingError("聲線模型名稱必填")
        job_request = StartRequest(
            corpus=corpus,
            name=name,
            voice=_optional_text(payload, "voice"),
            preset=_optional_text(payload, "preset"),
            sentences=_optional_text(payload, "sentences"),
        )
        snapshot = await asyncio.to_thread(_manager(request).start, job_request)
    except TrainingError as exc:
        extra = {"preflight": exc.preflight.to_dict()} if exc.preflight is not None else {}
        return _error(exc.message, exc.status, **extra, **exc.extra)
    except CorpusError as exc:
        return _error(exc.message, exc.status)
    return _json({"code": 0, "msg": "ok", "data": snapshot})


async def text_preview(request: web.Request) -> web.Response:
    """What a text list would be read as, sentence by sentence; touches no disk, network or model."""
    payload = await _json_object(request)
    if isinstance(payload, web.Response):
        return payload
    raw = payload.get("sentences")
    if not isinstance(raw, str):
        return _error("sentences 必須是文字", 400)
    try:
        review = await asyncio.to_thread(review_text_list, raw)
    except CorpusError as exc:
        return _error(exc.message, exc.status)
    data = {
        "ok": review.ok,
        "total": review.total,
        "unresolved_count": sum(len(item.unresolved) for item in review.sentences),
        "estimated_seconds": round(review.estimated_seconds, 1),
        "sentences": [
            {
                "index": item.index,
                "text": item.text,
                "spoken": item.spoken,
                "unresolved": [
                    {"text": u.text, "start": u.start, "end": u.end, "reason": u.reason} for u in item.unresolved
                ],
            }
            for item in review.sentences
        ],
    }
    return _json({"code": 0, "msg": "ok", "data": data})


async def voice_preview(request: web.Request) -> web.Response:
    """A preset sentence spoken by a finished voice model, as ``audio/wav`` (no custom text, no download)."""
    payload = await _json_object(request)
    if isinstance(payload, web.Response):
        return payload
    if set(payload) != {"voice_id", "sentence"}:
        return _error("只接受 voice_id 與 sentence 兩個欄位，不能自訂文字", 400)
    voice_id, sentence = payload["voice_id"], payload["sentence"]
    if not isinstance(voice_id, str) or not voice_id:
        return _error("voice_id 必須是聲線模型 ID", 400)
    if not isinstance(sentence, str) or sentence not in PREVIEW_SENTENCES:
        return _error("sentence 必須是 " + "、".join(PREVIEW_SENTENCES) + " 其中之一", 400)
    previewer: Previewer = request.app[PREVIEWER_KEY]
    stop = threading.Event()
    try:
        audio = await asyncio.wait_for(
            asyncio.to_thread(previewer, voice_id, sentence, lambda: not stop.is_set()),
            PREVIEW_TIMEOUT_SECONDS,
        )
    except asyncio.TimeoutError:  # a different class from the builtin before Python 3.11
        stop.set()
        return _error("試聽合成逾時，請稍後再試", 504)
    except asyncio.CancelledError:
        stop.set()
        raise
    except PreviewError as exc:
        return _error(exc.message, exc.status)
    except Exception:
        logger.exception("Voice preview failed")
        return _error("試聽合成時發生錯誤", 500)
    return web.Response(
        body=audio,
        content_type="audio/wav",
        headers={"Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"},
    )


async def cancel_job(request: web.Request) -> web.Response:
    snapshot = await asyncio.to_thread(_manager(request).cancel)
    return _json({"code": 0, "msg": "ok" if snapshot else "沒有進行中的訓練工作", "data": snapshot})


async def read_log(request: web.Request) -> web.Response:
    try:
        offset = int(request.query.get("offset", 0))
    except ValueError:
        return _error("offset 必須是整數", 400)
    if offset < 0:
        return _error("offset 不可為負數", 400)
    return _json({"code": 0, "data": await asyncio.to_thread(_manager(request).read_log, offset)})


async def _recover_jobs(app: web.Application) -> None:
    """At startup, before any request: fail interrupted jobs and stop the children they left."""
    await asyncio.to_thread(app[MANAGER_KEY].recover)


async def _stop_jobs(app: web.Application) -> None:
    """At shutdown: cancel the running job and kill its child, so the GPU is free when the server exits."""
    await asyncio.to_thread(app[MANAGER_KEY].shutdown)


def register(app: web.Application) -> None:
    app[MANAGER_KEY] = build_manager(app)
    app[PREVIEWER_KEY] = live_previewer
    app.on_startup.append(_recover_jobs)
    app.on_shutdown.append(_stop_jobs)
    app.router.add_get(PREFIX, get_status)
    app.router.add_post(PREFIX + "/start", start_job)
    app.router.add_post(PREFIX + "/text-preview", text_preview)
    app.router.add_post(PREFIX + "/preview", voice_preview)
    app.router.add_post(PREFIX + "/cancel", cancel_job)
    app.router.add_get(PREFIX + "/log", read_log)
